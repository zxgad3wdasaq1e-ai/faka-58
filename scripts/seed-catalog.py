def ensure_category(api: AdminAPI) -> int:
    path = "/admin/categories"
    categories = api.list_all(path)
    existing = next((row for row in categories if row.get("slug") == "chatgpt"), None)
    if existing is None:
        try:
            existing = api.request("POST", path, {
                "slug": "chatgpt", "parent_id": 0, "sort_order": 100,
                "name": localized("ChatGPT 服务", "ChatGPT 服務", "ChatGPT services"),
            }).get("data")
            print("Created category: chatgpt")
        except SeedError:
            # A concurrent seed may have created this slug. Never update it.
            existing = next((row for row in api.list_all(path) if row.get("slug") == "chatgpt"), None)
            if existing is None:
                raise
            print("Kept existing category: chatgpt")
    else:
        print("Kept existing category: chatgpt")
    if not isinstance(existing, dict) or not isinstance(existing.get("id"), int) or existing["id"] <= 0:
        raise SeedError("The ChatGPT category did not return a valid ID.")
    return existing["id"]


def seed(api: AdminAPI) -> None:
    current = api.request("GET", "/admin/settings?key=site_config").get("data")
    if not isinstance(current, dict):
        raise SeedError("The site configuration API did not return an object.")
    if current:
        print("Kept existing site settings.")
    else:
        api.request("PUT", "/admin/settings", {"key": "site_config", "value": site_settings(api.origin)})
        print("Initialized XIOEN AI site settings.")

    category_id = ensure_category(api)
    path = "/admin/products"
    existing_slugs = {row.get("slug") for row in api.list_all(path)}
    for product in catalog(category_id):
        slug = product["slug"]
        if slug in existing_slugs:
            print(f"Kept existing product: {slug}")
            continue
        try:
            api.request("POST", path, product)
        except SeedError:
            if not any(row.get("slug") == slug for row in api.list_all(path)):
                raise
            print(f"Kept existing product: {slug}")
        else:
            print(f"Created product: {slug} (zero stock)")
        existing_slugs.add(slug)
    print("Catalog ready. Import genuine inventory and configure live payment channels in the admin console before sales.")


def main() -> int:
    parser = argparse.ArgumentParser(description="Idempotently create the XIOEN AI catalog via the real admin API. Existing settings/products are preserved; no card secrets or payments are created.")
    parser.add_argument("--base-url", default="https://xioenai.vip", help="Application origin (default: https://xioenai.vip; local: http://localhost:8080)")
    parser.add_argument("--config", type=Path, default=ROOT / "config.yml", help="Private JSON-format YAML written by setup.py (default: repository config.yml)")
    parser.add_argument("--credentials-stdin", action="store_true", help="Read a JSON object with username/password or token from stdin instead of config/environment")
    args = parser.parse_args()
    try:
        api = AdminAPI(origin_url(args.base_url))
        api.login(credentials(args))
        seed(api)
        return 0
    except (SeedError, OSError, ValueError) as error:
        print(f"Catalog initialization stopped: {error}", file=sys.stderr)
        return 1
    except KeyboardInterrupt:
        print("Catalog initialization interrupted. Run again to resume safely.", file=sys.stderr)
        return 130


if __name__ == "__main__":
    raise SystemExit(main())
