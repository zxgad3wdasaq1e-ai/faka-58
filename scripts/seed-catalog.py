#!/usr/bin/env python3
"""Initialize the storefront through its admin API without replacing live data.

Credentials come from setup.py's JSON-format config.yml, environment variables,
or a JSON object on stdin. Passwords and tokens are never command-line options.
This script creates no payment channels, card secrets, orders, or payments.
"""
from __future__ import annotations

import argparse
import ipaddress
import json
import os
from pathlib import Path
import sys
import urllib.error
import urllib.parse
import urllib.request


ROOT = Path(__file__).resolve().parents[1]
MAX_RESPONSE_BYTES = 5 * 1024 * 1024


class SeedError(Exception):
    """An actionable error that does not contain private API payloads."""


class NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, request, response, code, message, headers, new_url):
        # Never forward a bootstrap password or bearer token to a redirect URL.
        return None


def origin_url(value: str) -> str:
    if any(character.isspace() or ord(character) < 32 for character in value.strip()):
        raise SeedError("--base-url must not contain whitespace or control characters.")
    parts = urllib.parse.urlsplit(value.strip())
    if (parts.scheme not in ("http", "https") or not parts.hostname
            or parts.username is not None or parts.password is not None
            or parts.path not in ("", "/") or parts.query or parts.fragment):
        raise SeedError("--base-url must be an HTTP(S) origin without credentials, a path, or a query.")
    try:
        parts.port
    except ValueError as error:
        raise SeedError("--base-url contains an invalid port.") from error
    if parts.scheme == "http":
        try:
            loopback = ipaddress.ip_address(parts.hostname).is_loopback
        except ValueError:
            loopback = parts.hostname.lower() == "localhost"
        if not loopback:
            raise SeedError("Use HTTPS for a remote API. HTTP is supported only for localhost or a loopback address.")
    return urllib.parse.urlunsplit((parts.scheme, parts.netloc, "", "", ""))


def credentials(args: argparse.Namespace) -> dict[str, str]:
    if args.credentials_stdin:
        raw = sys.stdin.read(65537)
        if len(raw) > 65536:
            raise SeedError("The credentials JSON on stdin is too large.")
        try:
            source = json.loads(raw)
        except json.JSONDecodeError as error:
            raise SeedError("stdin must contain a JSON object with username/password or token.") from error
    else:
        source = {
            "username": os.environ.get("XIOEN_ADMIN_USERNAME", ""),
            "password": os.environ.get("XIOEN_ADMIN_PASSWORD", ""),
            "token": os.environ.get("XIOEN_ADMIN_TOKEN", ""),
        }
        if not source["token"] and not (source["username"] and source["password"]):
            try:
                config = json.loads(args.config.read_text(encoding="utf-8-sig"))
            except FileNotFoundError as error:
                raise SeedError("Private config.yml was not found. Run setup.py first, or supply credentials via environment/stdin.") from error
            except json.JSONDecodeError as error:
                raise SeedError("--config expects the JSON-format YAML generated by setup.py. For other YAML files, supply credentials via environment/stdin.") from error
            if not isinstance(config, dict) or not isinstance(config.get("bootstrap"), dict):
                raise SeedError("The configuration has no bootstrap administrator credentials.")
            bootstrap = config["bootstrap"]
            source["username"] = source["username"] or bootstrap.get("default_admin_username", "")
            source["password"] = source["password"] or bootstrap.get("default_admin_password", "")
    if not isinstance(source, dict):
        raise SeedError("Administrator credentials must be a JSON object.")
    result = {key: source.get(key, "") for key in ("username", "password", "token")}
    if any(not isinstance(value, str) for value in result.values()):
        raise SeedError("Administrator credential fields must be strings.")
    if result["token"] and (not result["token"].isascii() or any(ord(character) <= 32 or ord(character) >= 127 for character in result["token"])):
        raise SeedError("The administrator token must be a raw ASCII token without whitespace.")
    if not result["token"] and not (result["username"] and result["password"]):
        raise SeedError("Supply a nonempty administrator username and password, or an existing admin token.")
    return result


class AdminAPI:
    def __init__(self, origin: str, timeout: float = 30):
        self.origin = origin
        self.timeout = timeout
        self.token = ""
        self.opener = urllib.request.build_opener(NoRedirect())

    def request(self, method: str, path: str, payload: dict | None = None) -> dict:
        headers = {"Accept": "application/json", "Accept-Language": "en-US"}
        data = None
        if payload is not None:
            headers["Content-Type"] = "application/json"
            data = json.dumps(payload, ensure_ascii=False).encode("utf-8")
        if self.token:
            headers["Authorization"] = "Bearer " + self.token
        request = urllib.request.Request(self.origin + "/api/v1" + path, data=data, headers=headers, method=method)
        endpoint = path.split("?", 1)[0]
        try:
            with self.opener.open(request, timeout=self.timeout) as response:
                raw = response.read(MAX_RESPONSE_BYTES + 1)
        except urllib.error.HTTPError as error:
            raise SeedError(f"{method} {endpoint} returned HTTP {error.code}. Verify the origin, authentication, and reverse proxy.") from None
        except (urllib.error.URLError, TimeoutError, OSError):
            raise SeedError(f"Cannot reach {method} {endpoint}. Check API availability and TLS; no security check was bypassed.") from None
        if len(raw) > MAX_RESPONSE_BYTES:
            raise SeedError(f"{method} {endpoint} returned an unexpectedly large response.")
        try:
            envelope = json.loads(raw)
        except (json.JSONDecodeError, UnicodeDecodeError):
            raise SeedError(f"{method} {endpoint} did not return JSON. Verify --base-url points to the application.") from None
        if not isinstance(envelope, dict) or envelope.get("status_code") != 0:
            # Do not echo server bodies: login responses can contain credentials.
            code = envelope.get("status_code") if isinstance(envelope, dict) else None
            if not isinstance(code, int):
                code = "invalid"
            raise SeedError(f"{method} {endpoint} was rejected (status_code={code}). Check credentials, RBAC, captcha/2FA, and server logs.")
        return envelope

    def login(self, secret: dict[str, str]) -> None:
        if secret["token"]:
            self.token = secret["token"]
            return
        data = self.request("POST", "/admin/login", {
            "username": secret["username"], "password": secret["password"],
        }).get("data")
        if not isinstance(data, dict):
            raise SeedError("The administrator login response is invalid.")
        if data.get("requires_totp"):
            raise SeedError("This administrator requires 2FA. Complete login normally and provide its token via XIOEN_ADMIN_TOKEN or stdin.")
        if not isinstance(data.get("token"), str) or not data["token"]:
            raise SeedError("Administrator login did not return a token.")
        self.token = data["token"]

    def list_all(self, path: str) -> list[dict]:
        rows: list[dict] = []
        page = 1
        while True:
            separator = "&" if "?" in path else "?"
            response = self.request("GET", f"{path}{separator}page={page}&page_size=100")
            data = response.get("data")
            if data is None:
                data = []
            if not isinstance(data, list) or any(not isinstance(item, dict) for item in data):
                raise SeedError(f"The list returned by {path} is invalid.")
            rows.extend(data)
            pagination = response.get("pagination")
            if not pagination:
                return rows
            if not isinstance(pagination, dict):
                raise SeedError(f"The pagination returned by {path} is invalid.")
            total_pages = pagination.get("total_page", 0)
            if not isinstance(total_pages, int) or total_pages < 0:
                raise SeedError(f"The pagination returned by {path} is invalid.")
            if page >= total_pages:
                return rows
            if not data or page >= 10000:
                raise SeedError(f"The pagination returned by {path} did not finish safely.")
            page += 1


